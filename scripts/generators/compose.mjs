import { mkdir, rm } from "node:fs/promises";
import path from "node:path";
import { iconPathData, iconSubpaths, round } from "./native-paths.mjs";
import { write } from "./shared.mjs";

const float = (value) => `${round(value)}f`;
const point = ([x, y]) => `${float(x)}, ${float(y)}`;

function pathBuilder(icon) {
  const lines = [];
  for (const subpath of iconSubpaths(icon)) {
    lines.push(`moveTo(${point(subpath.start)})`);
    for (const segment of subpath.segments) {
      if (segment.closing) continue;
      if (segment.type === "L") lines.push(`lineTo(${point(segment.to)})`);
      else if (segment.type === "C") lines.push(`curveTo(${point(segment.c1)}, ${point(segment.c2)}, ${point(segment.to)})`);
      else if (segment.type === "Q") lines.push(`quadTo(${point(segment.c)}, ${point(segment.to)})`);
      else lines.push(`arcTo(${float(segment.rx)}, ${float(segment.ry)}, ${float(segment.rotation)}, ${segment.largeArc}, ${segment.sweep}, ${point(segment.to)})`);
    }
    if (subpath.closed) lines.push("close()");
  }
  return lines.map((line) => `        ${line}`).join("\n");
}

export function drawableName(icon) {
  return `vadivam_${icon.name.replace(/-/g, "_")}`;
}

// Same geometry as the SVG, for View-based apps and anything that takes a
// drawable resource. Tinted with colorControlNormal like Material icons.
export function vectorDrawable(icon) {
  return `<?xml version="1.0" encoding="utf-8"?>\n<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="24dp"\n    android:height="24dp"\n    android:viewportWidth="24"\n    android:viewportHeight="24"\n    android:tint="?android:attr/colorControlNormal">\n  <path\n      android:pathData="${iconPathData(icon)}"\n      android:fillColor="#00000000"\n      android:strokeColor="@android:color/white"\n      android:strokeWidth="2"\n      android:strokeLineCap="round"\n      android:strokeLineJoin="round"/>\n</vector>\n`;
}

export async function buildComposePackage(icons, packageDirectory) {
  const iconsDirectory = path.join(packageDirectory, "src/main/kotlin/com/praveenjuge/vadivam/icons");
  const drawables = path.join(packageDirectory, "src/main/res/drawable");
  await rm(iconsDirectory, { recursive: true, force: true });
  await rm(path.join(packageDirectory, "src/main/res"), { recursive: true, force: true });
  await mkdir(iconsDirectory, { recursive: true });
  await mkdir(drawables, { recursive: true });
  for (const icon of icons) {
    const backing = `_${icon.componentName}`;
    await write(iconsDirectory, `${icon.componentName}.kt`, `// Generated by scripts/icons.mjs. Do not edit.\npackage com.praveenjuge.vadivam.icons\n\nimport androidx.compose.ui.graphics.vector.ImageVector\nimport com.praveenjuge.vadivam.VadivamIcons\nimport com.praveenjuge.vadivam.vadivamIcon\n\n/** [${icon.name}](https://vadivam.praveenjuge.com/icons/${icon.name}) */\npublic val VadivamIcons.${icon.componentName}: ImageVector\n    get() = ${backing} ?: vadivamIcon("${icon.componentName}") {\n${pathBuilder(icon)}\n    }.also { ${backing} = it }\n\nprivate var ${backing}: ImageVector? = null\n`);
    await write(drawables, `${drawableName(icon)}.xml`, vectorDrawable(icon));
  }
  // Filled in chunks: one function holding every entry would pass the JVM's
  // 64 KB method size limit.
  const chunks = [];
  for (let index = 0; index < icons.length; index += 200) chunks.push(icons.slice(index, index + 200));
  const fills = chunks.map((chunk, index) => `private fun fill${index}(map: HashMap<String, () -> ImageVector>) {\n${chunk.map((icon) => `    map["${icon.name}"] = { VadivamIcons.${icon.componentName} }`).join("\n")}\n}`);
  await write(iconsDirectory, "ByName.kt", `// Generated by scripts/icons.mjs. Do not edit.\npackage com.praveenjuge.vadivam.icons\n\nimport androidx.compose.ui.graphics.vector.ImageVector\nimport com.praveenjuge.vadivam.VadivamIcons\n\nprivate val iconsByName: Map<String, () -> ImageVector> by lazy {\n    HashMap<String, () -> ImageVector>(${icons.length * 2}).also { map ->\n${chunks.map((_, index) => `        fill${index}(map)`).join("\n")}\n    }\n}\n\n/** Every icon name, such as \`arrow-right\`. */\npublic val VadivamIcons.names: Set<String> get() = iconsByName.keys\n\n/**\n * Looks up an icon by its kebab-case name, such as \`arrow-right\`. Calling this\n * keeps every icon in the app, so prefer the named properties when you can.\n */\npublic fun VadivamIcons.byName(name: String): ImageVector? = iconsByName[name]?.invoke()\n\n${fills.join("\n\n")}\n`);
}
