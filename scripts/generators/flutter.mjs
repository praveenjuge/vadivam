import { mkdir, readFile, rm } from "node:fs/promises";
import path from "node:path";
import { styles } from "../icon-styles.mjs";
import { dartIconName, iconsOwner } from "../package-names.mjs";
import { repositoryUrl, siteUrl, targetsById } from "../packages.mjs";
import { iconSubpaths, round } from "./native-paths.mjs";
import { write } from "./shared.mjs";

// Opcodes match VadivamPathOp in packages/vadivam-flutter/lib/src/vadivam_icon.dart,
// which decodes them; change both together.
const ops = { move: 0, line: 1, cubic: 2, quad: 3, arc: 4, close: 5 };

function commands(icon) {
  const values = [];
  for (const subpath of iconSubpaths(icon)) {
    values.push(ops.move, ...subpath.start);
    for (const segment of subpath.segments) {
      if (segment.closing) continue;
      if (segment.type === "L") values.push(ops.line, ...segment.to);
      else if (segment.type === "C") values.push(ops.cubic, ...segment.c1, ...segment.c2, ...segment.to);
      else if (segment.type === "Q") values.push(ops.quad, ...segment.c, ...segment.to);
      else values.push(ops.arc, segment.rx, segment.ry, segment.rotation, segment.largeArc ? 1 : 0, segment.sweep ? 1 : 0, ...segment.to);
    }
    if (subpath.closed) values.push(ops.close);
  }
  return values.map(round).join(", ");
}

export async function build({ iconsByStyle, directory: packageDirectory }) {
  // pub.dev wants the changelog to name the version being published; the full
  // notes live on the docs site, shared by every package.
  const { versionFile, versionPattern } = targetsById.flutter;
  const version = (await readFile(path.join(packageDirectory, path.basename(versionFile)), "utf8")).match(versionPattern)[1].trim();
  await write(packageDirectory, "CHANGELOG.md", `# Changelog\n\n## ${version}\n\nVadivam releases every package together. See the notes for [v${version}](${repositoryUrl}/releases/tag/v${version}) and the full [changelog](${siteUrl}/changelog).\n`);
  const generated = path.join(packageDirectory, "lib/src/generated");
  await rm(generated, { recursive: true, force: true });
  await mkdir(generated, { recursive: true });
  for (const style of Object.values(styles)) {
    await write(generated, `${[style.entryDirectory, "icons"].filter(Boolean).join("_")}.dart`, iconsClass(iconsByStyle[style.id], style));
  }
}

// One class of constants per style: VadivamIcons, VadivamSolidIcons. The docs
// site serves each style's SVGs under its source folder's name.
function iconsClass(icons, style) {
  const className = iconsOwner(style);
  const description = style.stroked ? "Every Vadivam icon" : `The ${style.id} twin of every Vadivam icon, filled instead of stroked`;
  const flag = style.stroked ? "" : ", filled: true";
  const fields = icons.map((icon) => `  /// ![${icon.name}](${siteUrl}/${style.sourceDirectory}/${icon.name}.svg) [${icon.name}](${siteUrl}/icons/${icon.name})\n  static const ${dartIconName(icon.componentName)} = VadivamIconData('${icon.name}', [${commands(icon)}]${flag});`);
  const entries = icons.map((icon) => `    '${icon.name}': ${dartIconName(icon.componentName)},`);
  return `// Generated by scripts/icons.mjs. Do not edit.\n// ignore_for_file: public_member_api_docs\n\nimport '../vadivam_icon.dart';\n\n/// ${description}. Unused icons are tree-shaken from release builds.\nabstract final class ${className} {\n${fields.join("\n\n")}\n\n  /// Every icon by kebab-case name. Referencing this keeps all icons in the build.\n  static const Map<String, VadivamIconData> all = {\n${entries.join("\n")}\n  };\n}\n`;
}
